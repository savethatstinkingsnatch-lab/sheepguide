function getChapter(slug) {
	return CHAPTERS.find((chapter) => chapter.slug === slug);
}
function chapterIndex(slug) {
	return CHAPTERS.findIndex((chapter) => chapter.slug === slug);
}
function readMinutes(chapter) {
	const words = chapter.blocks.map((block) => {
		if (block.type === "p" || block.type === "h") return block.text;
		if (block.type === "list") return block.items.join(" ");
		if (block.type === "callout") return `${block.callout.title} ${block.callout.body}`;
		if (block.type === "stats") return block.items.map((item) => `${item.value} ${item.label}`).join(" ");
		if (block.type === "table") return block.rows.flat().join(" ");
		return block.items.map((item) => `${item.term} ${item.meaning}`).join(" ");
	}).join(" ").split(/\s+/).filter(Boolean).length;
	return Math.max(3, Math.round(words / 220));
}
function headingId(text, index) {
	return text.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "") || `section-${index}`;
}
